package com.veenaacharya.agentic.orchestrator.state;

import static org.assertj.core.api.Assertions.assertThat;

import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.boot.WebApplicationType;
import org.springframework.boot.builder.SpringApplicationBuilder;
import org.springframework.context.ConfigurableApplicationContext;

/** A database file written by an earlier version must still start; unit tests on fresh schemas cannot show this. */
class SchemaUpgradeTest {

    @TempDir
    Path dir;

    @Test
    void existingDatabaseWithRowsGainsTheNewColumnsWithoutLosingData() throws SQLException {
        String url = "jdbc:h2:file:" + dir.resolve("old").toString().replace('\\', '/');
        try (Connection c = DriverManager.getConnection(url, "sa", ""); Statement s = c.createStatement()) {
            // The stage_execution table as section 4 created it: no revision, hashes or feedback columns.
            s.execute("create table stage_execution (id bigint generated by default as identity primary key, "
                    + "attempt integer not null, error varchar(2000), finished_at timestamp(6) with time zone, "
                    + "output clob, run_id varchar(255) not null, stage_id varchar(255) not null, "
                    + "started_at timestamp(6) with time zone, status varchar(32) not null, commit_sha varchar(255))");
            s.execute("insert into stage_execution (attempt, run_id, stage_id, status) "
                    + "values (1, 'old-run', 'requirements', 'SUCCEEDED')");
        }

        try (ConfigurableApplicationContext ignored = new SpringApplicationBuilder(
                com.veenaacharya.agentic.orchestrator.OrchestratorApplication.class)
                .web(WebApplicationType.NONE)
                .run("--spring.datasource.url=" + url, "--orchestrator.workspace.root=" + dir.toString().replace('\\', '/'),
                        "--orchestrator.audit.dir=" + dir.resolve("audit").toString().replace('\\', '/'))) {
            // Starting the context runs the schema update.
        }

        try (Connection c = DriverManager.getConnection(url, "sa", ""); Statement s = c.createStatement();
             ResultSet rs = s.executeQuery("select stage_id, status, revision from stage_execution")) {
            assertThat(rs.next()).isTrue();
            assertThat(rs.getString("stage_id")).isEqualTo("requirements");
            assertThat(rs.getString("status")).isEqualTo("SUCCEEDED");
            assertThat(rs.getInt("revision")).isEqualTo(1);
            assertThat(rs.next()).isFalse();
        }
    }
}
