CREATE TABLE IF NOT EXISTS links (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    short_code   VARCHAR(16)   NOT NULL,
    long_url     VARCHAR(2048) NOT NULL,
    click_count  BIGINT        NOT NULL DEFAULT 0,
    created_at   TIMESTAMP     NOT NULL,
    CONSTRAINT uk_links_short_code UNIQUE (short_code),
    CONSTRAINT ck_links_click_count_non_negative CHECK (click_count >= 0)
);

ALTER TABLE links ADD COLUMN IF NOT EXISTS expires_at TIMESTAMP;
CREATE INDEX IF NOT EXISTS idx_links_expires_at ON links(expires_at);

CREATE TABLE IF NOT EXISTS click_event (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    link_id       BIGINT       NOT NULL,
    clicked_at    TIMESTAMP    NOT NULL,
    referrer_host VARCHAR(253) NULL,
    ua_category   VARCHAR(16)  NOT NULL,
    CONSTRAINT fk_click_event_link FOREIGN KEY (link_id) REFERENCES links (id) ON DELETE CASCADE,
    CONSTRAINT ck_click_event_ua_category CHECK (ua_category IN ('BROWSER', 'BOT', 'OTHER'))
);

CREATE INDEX IF NOT EXISTS idx_click_event_link_time ON click_event (link_id, clicked_at);
